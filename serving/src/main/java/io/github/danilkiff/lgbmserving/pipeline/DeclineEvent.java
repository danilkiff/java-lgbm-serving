package io.github.danilkiff.lgbmserving.pipeline;

/**
 * Выкладывается вне горячего пути на каждое отклонение. Воркер explain считает
 * по нему нативный SHAP и сохраняет коды причин. Строка и версия модели
 * позволяют посчитать объяснение той же моделью, что приняла решение, поэтому
 * оно не может разойтись с решением.
 */
public record DeclineEvent(String id, double[] row, double margin, String modelVer) {

    /**
     * Строка копируется: событие живёт дольше вызова, а вызывающий переиспользует
     * массив - алиас дал бы объяснение чужого входа.
     */
    public DeclineEvent {
        row = row.clone();
    }
}
